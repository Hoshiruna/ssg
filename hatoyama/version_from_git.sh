#!/bin/sh
set -e
# Since Tup refuses to depend on files inside `.git/`…

version_fn="obj/version.h"
version_tag="(unknown)"

if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
	tag=$(git describe --tags --exact-match HEAD 2>/dev/null || true)

	if ! { git diff-index --quiet HEAD -- && [ -n "$tag" ]; }; then
		desc=$(git describe --tags --abbrev=0 2>/dev/null || true)
		commit=$(git rev-parse --short=4 HEAD)
		version_tag="WIP (${desc:+$desc^}$commit)"
	else
		version_tag="$tag"
	fi
fi

mkdir -p "$(dirname "$version_fn")"
# Preserve the timestamp when Git's version information has not changed.
version_tmp=$(mktemp "$version_fn.XXXXXX")
trap 'rm -f "$version_tmp"' EXIT HUP INT TERM
version_tag=$(printf '%s' "$version_tag" | sed 's/\\/\\\\/g; s/"/\\"/g')
{
	printf '// Generated by `%s`.\n' "$0"
	printf '#define VERSION_TAG "%s"\n' "$version_tag"
} > "$version_tmp"
if ! cmp -s "$version_tmp" "$version_fn"; then
	mv "$version_tmp" "$version_fn"
fi
